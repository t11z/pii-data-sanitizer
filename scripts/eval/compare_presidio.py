#!/usr/bin/env python3
"""Compare Microsoft Presidio against this project's heuristic engine on the SAME
labeled corpus (bench/corpus.json) using the SAME strict, span-level metric.

This is an eval-time tool only — it adds no runtime dependency, and the browser app
stays 100% offline. See docs/comparison.md.

Usage:
    python3 -m venv .venv && source .venv/bin/activate
    pip install presidio-analyzer
    python -m spacy download en_core_web_lg
    python scripts/eval/compare_presidio.py [--write]
"""
from __future__ import annotations

import json
import sys
import unicodedata
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CORPUS = ROOT / "bench" / "corpus.json"

# Presidio entity label -> this project's PiiType. Types this project does not model
# (or Presidio does not detect, e.g. MAC) are simply absent and never matched.
LABEL_MAP = {
    "EMAIL_ADDRESS": "EMAIL",
    "PHONE_NUMBER": "PHONE",
    "IBAN_CODE": "IBAN",
    "CREDIT_CARD": "CREDIT_CARD",
    "IP_ADDRESS": "IP",
    "PERSON": "PERSON",
}
# Types both systems are scored on (intersection of what each can produce).
SCORED_TYPES = sorted(set(LABEL_MAP.values()))


def nfc(s: str) -> str:
    return unicodedata.normalize("NFC", s)


def key(pii_type: str, text: str) -> str:
    return f"{pii_type}|{nfc(text)}"


def prf(tp: int, fp: int, fn: int) -> tuple[float, float, float]:
    precision = 1.0 if tp + fp == 0 else tp / (tp + fp)
    recall = 1.0 if tp + fn == 0 else tp / (tp + fn)
    f1 = 0.0 if precision + recall == 0 else 2 * precision * recall / (precision + recall)
    return precision, recall, f1


def main() -> int:
    try:
        from presidio_analyzer import AnalyzerEngine
    except ImportError:
        print(
            "presidio-analyzer is not installed.\n"
            "  pip install presidio-analyzer && python -m spacy download en_core_web_lg",
            file=sys.stderr,
        )
        return 2

    cases = json.loads(CORPUS.read_text(encoding="utf-8"))
    analyzer = AnalyzerEngine()

    overall = {"tp": 0, "fp": 0, "fn": 0}
    per: dict[str, dict[str, int]] = defaultdict(lambda: {"tp": 0, "fp": 0, "fn": 0})

    for case in cases:
        text = case["text"]
        # Only score entity types both systems can produce.
        expected = {
            key(e["type"], e["text"]) for e in case["entities"] if e["type"] in SCORED_TYPES
        }
        results = analyzer.analyze(text=text, language="en")
        detected = set()
        for r in results:
            mapped = LABEL_MAP.get(r.entity_type)
            if mapped is None:
                continue
            detected.add(key(mapped, text[r.start : r.end]))

        for k in expected:
            t = k.split("|", 1)[0]
            if k in detected:
                overall["tp"] += 1
                per[t]["tp"] += 1
            else:
                overall["fn"] += 1
                per[t]["fn"] += 1
        for k in detected:
            if k not in expected:
                t = k.split("|", 1)[0]
                overall["fp"] += 1
                per[t]["fp"] += 1

    lines = ["| Type | Precision | Recall | F1 | TP | FP | FN |", "| --- | --- | --- | --- | --- | --- | --- |"]
    for t in SCORED_TYPES:
        c = per[t]
        p, r, f = prf(c["tp"], c["fp"], c["fn"])
        lines.append(
            f"| {t} | {p*100:.1f}% | {r*100:.1f}% | {f*100:.1f}% | {c['tp']} | {c['fp']} | {c['fn']} |"
        )
    p, r, f = prf(overall["tp"], overall["fp"], overall["fn"])
    lines.append(
        f"| **Overall** | {p*100:.1f}% | {r*100:.1f}% | {f*100:.1f}% | "
        f"{overall['tp']} | {overall['fp']} | {overall['fn']} |"
    )
    table = "\n".join(lines)

    print(f"\nPresidio on bench/corpus.json (scored types: {', '.join(SCORED_TYPES)})\n")
    print(table)

    if "--write" in sys.argv:
        out = ROOT / "docs" / "comparison-report.md"
        out.write_text(
            "# Presidio comparison report\n\n"
            "<!-- Generated by scripts/eval/compare_presidio.py --write. -->\n\n"
            f"Scored on the intersection of detectable types: {', '.join(SCORED_TYPES)}.\n\n"
            f"{table}\n",
            encoding="utf-8",
        )
        print(f"\nWrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
